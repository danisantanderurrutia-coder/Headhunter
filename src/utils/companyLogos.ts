/**
 * Extracts the canonical root domain from complex hostnames,
 * ensuring subdomains like jobs.ethz.ch or c4land.kit.edu resolve to their main entity domain.
 */
export const extractRootDomain = (hostname: string): string => {
  const clean = hostname.replace(/^www\./, '').toLowerCase();
  const parts = clean.split('.');
  if (parts.length <= 2) return clean;

  if (clean.endsWith('.kit.edu')) return 'kit.edu';
  if (clean.endsWith('.euskadi.eus')) return 'euskadi.eus';
  if (clean.endsWith('.ac.at')) return parts.slice(-3).join('.');
  if (clean.endsWith('.mpg.de')) return 'mpg.de';
  if (clean.endsWith('.co.uk')) return parts.slice(-3).join('.');

  return parts.slice(-2).join('.');
};

export interface ResolvedLogoDetails {
  primaryUrl?: string;
  fallbackFaviconUrl: string;
  fallbackDdgUrl: string;
  initials: string;
}

export const resolveCompanyLogoDetails = (company: {
  id?: string;
  website?: string;
  name: string;
  logoUrl?: string;
}): ResolvedLogoDetails => {
  const initials = company.name
    .replace(/^(the|el|la|los|las|de|von|der)\s+/i, '')
    .split(/[\s-]+/)
    .filter(w => w.length > 0)
    .slice(0, 2)
    .map(w => w[0].toUpperCase())
    .join('');

  let domain = '';
  let rootDomain = '';

  if (company.website) {
    try {
      const url = company.website.startsWith('http') ? company.website : `https://${company.website}`;
      domain = new URL(url).hostname.replace(/^www\./, '');
      rootDomain = extractRootDomain(domain);
    } catch {
      // Ignore URL parse error
    }
  }

  const primaryUrl = company.logoUrl || (company.id && COMPANY_CURATED_LOGOS[company.id]);
  const targetDomain = rootDomain || domain;

  const fallbackFaviconUrl = targetDomain
    ? `https://www.google.com/s2/favicons?domain=${targetDomain}&sz=128`
    : '';

  const fallbackDdgUrl = targetDomain
    ? `https://icons.duckduckgo.com/ip3/${targetDomain}.ico`
    : '';

  return {
    primaryUrl,
    fallbackFaviconUrl,
    fallbackDdgUrl,
    initials
  };
};
